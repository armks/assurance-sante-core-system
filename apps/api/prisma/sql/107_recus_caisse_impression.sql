-- Paramétrage de l'impression (imprimante thermique 58/80 mm ou A4) par établissement sanitaire ou pharmacie,
-- et reçus de caisse émis lorsque le patient règle sa facture (numérotation continue, duplicata tracés).
create table if not exists public.parametres_impression (
  id                 uuid primary key default gen_random_uuid(),
  organisation_id    uuid not null references public.organisations (id) on delete cascade,
  etablissement_id   uuid references public.etablissements_sante (id) on delete cascade,
  pharmacie_id       uuid references public.pharmacies (id) on delete cascade,
  type_imprimante    text not null default 'A4' check (type_imprimante in ('THERMIQUE_58', 'THERMIQUE_80', 'A4')),
  en_tete            text check (en_tete is null or char_length(en_tete) <= 300),
  pied_page          text check (pied_page is null or char_length(pied_page) <= 300),
  identifiant_fiscal text check (identifiant_fiscal is null or char_length(identifiant_fiscal) <= 60),
  afficher_detail    boolean not null default true,
  updated_by         uuid references public.profils (id) on delete set null,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  check ((etablissement_id is not null) <> (pharmacie_id is not null))
);
create unique index if not exists parametres_impression_etab_uq on public.parametres_impression (etablissement_id) where etablissement_id is not null;
create unique index if not exists parametres_impression_pharm_uq on public.parametres_impression (pharmacie_id) where pharmacie_id is not null;

create table if not exists public.recus_caisse (
  id                  uuid primary key default gen_random_uuid(),
  organisation_id     uuid not null references public.organisations (id) on delete cascade,
  etablissement_id    uuid references public.etablissements_sante (id),
  pharmacie_id        uuid references public.pharmacies (id),
  facture_id          uuid unique references public.factures_dossier (id) on delete cascade,
  dispensation_id     uuid unique references public.dispensations_pharmacie (id) on delete cascade,
  numero_seq          integer generated by default as identity unique,
  numero              text not null unique,
  montant_paye        numeric(14, 2) not null check (montant_paye >= 0),
  date_paiement       timestamptz not null,
  emis_par            uuid references public.profils (id) on delete set null,
  nombre_impressions  integer not null default 0,
  derniere_impression timestamptz,
  created_at          timestamptz not null default now(),
  check ((facture_id is not null) <> (dispensation_id is not null)),
  check ((etablissement_id is not null) <> (pharmacie_id is not null))
);
create index if not exists recus_caisse_org_idx on public.recus_caisse (organisation_id);

-- aucune lecture directe via PostgREST : l'accès passe uniquement par l'API
alter table public.parametres_impression enable row level security;
alter table public.recus_caisse enable row level security;
